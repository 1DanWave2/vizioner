def fallback_description(work: dict) -> str:
    """Запасное описание если работы нет в DESCRIPTIONS."""
    genre = (work.get("genre") or "").lower()
    title = work.get("title", "")
    artist = work.get("artist", "")
    if "пейзаж" in genre:
        return f"Пейзажная работа — «{title}». Классическая школа русской живописи маслом, спокойная палитра. Подойдёт в гостиную или кабинет."
    if "натюрморт" in genre:
        return f"Натюрморт — «{title}». Живая композиция, насыщенный цвет. Хорошо смотрится в столовой, кухне или гостиной."
    if "портрет" in genre:
        return f"Жанровый портрет — «{title}». Работа с характером, классическое письмо. В кабинет, библиотеку, гостевую."
    return f"Работа маслом — «{title}». Подойдёт в гостиную или кабинет в классическом интерьере."


def main():
    dry = "--dry-run" in sys.argv

    works = json.loads(WORKS.read_text(encoding="utf-8"))

    if not dry:
        BACKUP.parent.mkdir(exist_ok=True)
        BACKUP.write_text(json.dumps(works, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"[backup] {BACKUP}")

    rows = []
    for w in works:
        price, label = price_for(w)
        desc = DESCRIPTIONS.get(w["id"]) or fallback_description(w)

        rows.append((w["id"], w["title"], w["artist"], w.get("size", ""), label))

        if not dry:
            w["price"] = price
            w["price_label"] = label
            w["description"] = desc

    if not dry:
        WORKS.write_text(
            json.dumps(works, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"[save] {WORKS}")

    print("\n=== Стартовые цены ===")
    print(f"{'ID':<30} {'Художник':<12} {'Размер':<12} {'Цена'}")
    print("-" * 78)
    for r in rows:
        print(f"{r[0]:<30} {r[2]:<12} {r[3]:<12} {r[4]}")

    if dry:
        print("\n[dry-run] works.json НЕ изменён. Убери --dry-run чтобы применить.")
    else:
        print("\n[OK] Применено. Проверь на сайте, правки делай через admin.html.")


if __name__ == "__main__":
    main()
