ARTIST_MULTIPLIER = {
    "Изумрудов": 1.4,
    "Есенов":    1.4,
    "Углач":     1.0,
    "Шугаев":    1.0,
}


def base_price_for_area(area_cm2: int) -> int:
    """Базовая стартовая цена по площади холста, шкала под нишу 50-300к."""
    if area_cm2 < 3000:    return 45_000   # 50×60 и меньше
    if area_cm2 < 4500:    return 55_000   # 60×70
    if area_cm2 < 6000:    return 70_000   # 70×80
    if area_cm2 < 9000:    return 95_000   # 80×100
    if area_cm2 < 13000:   return 140_000  # 100×120
    if area_cm2 < 17000:   return 200_000  # 110×130, 120×140
    return 280_000                          # 130×150+


def round_to_5k(price: int) -> int:
    return int(round(price / 5000)) * 5000


def price_for(work: dict) -> tuple[int, str]:
    w = work.get("size_w") or 60
    h = work.get("size_h") or 70
    area = w * h
    artist = work.get("artist", "")
    mult = ARTIST_MULTIPLIER.get(artist, 1.0)
    raw = base_price_for_area(area) * mult
    final = round_to_5k(int(raw))
    label = f"от {final:,} ₽".replace(",", " ")
    return final, label


